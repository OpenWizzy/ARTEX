function TaskControlButton({
  task,
  onControl,
}: {
  task: Task;
  onControl: (id: string, action: "pause" | "resume") => Promise<void>;
}) {
  const [pending, setPending] = React.useState(false);
  const { t } = useLingui();
  const action = taskControlAction(task.status);
  const label = action === "resume" ? t`Resume task` : t`Pause task`;
  return (
    <Button
      size="icon"
      variant="ghost"
      aria-label={label}
      title={action ? label : t`This status can't be paused or resumed`}
      disabled={!action || pending}
      onClick={async () => {
        if (!action) return;
        setPending(true);
        try {
          await onControl(task.id, action);
        } finally {
          setPending(false);
        }
      }}
    >
      {taskControlIcon(pending, action)}
    </Button>
  );
}

function archiveBlockReason(task: Task): string {
  if (task.queued) return tr(msg`Queued tasks must be paused first`);
  if (!ARCHIVABLE_STATUSES.has(task.status)) return tr(msg`Running or unfinished tasks must be paused first`);
  if (task.archive_blocked_by_task_id) {
    const blockerId = task.archive_blocked_by_task_id;
    return tr(msg`This task is directly inherited by un-archived task #${blockerId}; archive the dependency first`);
  }
  return "";
}

